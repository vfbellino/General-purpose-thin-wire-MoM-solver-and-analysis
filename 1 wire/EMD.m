% This function computes the full-wave electromagnetic field given the
% current distribution on a dipole of given length and given radius.
% In input the following is needed.

% 1) (lamb) wavelength of the radiated wave.
% 2) (zmid) the points where the current is defined.
% 3) (I) the current distribution.
% 4) (r) the vector of radius.
% 5) (phi) the vector of azimuth angle.
% 6) (tht) the vector of co-latitude angles.

function [E,H] = EMD(lamb,zmid,I,r,phi,tht)

e = 8.8541878128e-12;
k = 2*pi/lamb;
ome = k*physconst('LightSpeed');

[R,PHI,THT] = meshgrid(r,phi,tht);

dz = zmid(2)-zmid(1);
Q = length(zmid);
w = dz*ones(Q,1);

R0 = @(r,tht,zmid) sqrt(r.^2 + zmid.^2 - 2*r.*zmid.*cos(tht));

KHphi = @(r,phi,tht,zmid) ...
    (r.*sin(tht))./(4*pi) .* ...
    exp(-1i*k.*R0(r,tht,zmid)) .* ...
    (1 + 1i*k.*R0(r,tht,zmid)) ./ ...
    R0(r,tht,zmid).^3;

KEr = @(r,phi,tht,zmid) ...
    -1i./(4*pi*ome*e) .* ...
    exp(-1i*k.*R0(r,tht,zmid)) .* ...
    ( ...
    r.*sin(tht).^2 .* (r.*cos(tht)-zmid) .* ...
    ( ...
    3.*(1 + 1i*k.*R0(r,tht,zmid))./R0(r,tht,zmid).^5 ...
    - k^2./R0(r,tht,zmid).^3 ...
    ) ...
    + ...
    cos(tht) .* ...
    ( ...
    k^2.*r.^2.*sin(tht).^2 ./ R0(r,tht,zmid).^3 ...
    + ...
    (1 + 1i*k.*R0(r,tht,zmid)) .* ...
    ( ...
    2.*(r.*cos(tht)-zmid).^2 ...
    - r.^2.*sin(tht).^2 ...
    ) ./ R0(r,tht,zmid).^5 ...
    ) ...
    );

KEtht = @(r,phi,tht,zmid) ...
    -1i./(4*pi*ome*e) .* ...
    exp(-1i*k.*R0(r,tht,zmid)) .* ...
    ( ...
    r.*sin(tht).*cos(tht).*(r.*cos(tht)-zmid) .* ...
    ( ...
    3.*(1 + 1i*k.*R0(r,tht,zmid))./R0(r,tht,zmid).^5 ...
    - k^2./R0(r,tht,zmid).^3 ...
    ) ...
    - ...
    sin(tht) .* ...
    ( ...
    k^2.*r.^2.*sin(tht).^2 ./ R0(r,tht,zmid).^3 ...
    + ...
    (1 + 1i*k.*R0(r,tht,zmid)) .* ...
    ( ...
    2.*(r.*cos(tht)-zmid).^2 ...
    - r.^2.*sin(tht).^2 ...
    ) ./ R0(r,tht,zmid).^5 ...
    ) ...
    );

Z4 = reshape(zmid,1,1,1,Q);
I4 = reshape(I,1,1,1,Q);
W4 = reshape(w,1,1,1,Q);

KH = KHphi(R,PHI,THT,Z4);
Hp = sum(W4 .* I4 .* KH,4);

KE1 = KEr(R,PHI,THT,Z4);
Er = sum(W4 .* I4 .* KE1,4);

KE2 = KEtht(R,PHI,THT,Z4);
Et = sum(W4 .* I4 .* KE2,4);

[m,n,l] = size(Et);

Hr = zeros(m,n,l);
Ht = zeros(m,n,l);
Ep = zeros(m,n,l);

E = struct('rad',Er,'azim',Ep,'co_lat',Et);
H = struct('rad',Hr,'azim',Hp,'co_lat',Ht);


