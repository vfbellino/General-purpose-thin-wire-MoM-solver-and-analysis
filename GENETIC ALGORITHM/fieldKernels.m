function Kf = fieldKernels(medium)

eps   = medium.eps;
k     = medium.wavenumb;
omega = medium.omega;

R0 = @(r,th,smid) sqrt(r.^2 + smid.^2 - 2*r.*smid.*cos(th));

KHph = @(r,ph,th,smid) ...
    (r.*sin(th))./(4*pi) .* ...
    exp(-1i*k.*R0(r,th,smid)) .* ...
    (1 + 1i*k.*R0(r,th,smid)) ./ ...
    R0(r,th,smid).^3;

KEr = @(r,ph,th,smid) ...
    -1i./(4*pi*omega*eps) .* ...
    exp(-1i*k.*R0(r,th,smid)) .* ...
    ( ...
    r.*sin(th).^2 .* (r.*cos(th)-smid) .* ...
    ( ...
    3.*(1 + 1i*k.*R0(r,th,smid))./R0(r,th,smid).^5 ...
    - k^2./R0(r,th,smid).^3 ...
    ) ...
    + ...
    cos(th) .* ...
    ( ...
    k^2.*r.^2.*sin(th).^2 ./ R0(r,th,smid).^3 ...
    + ...
    (1 + 1i*k.*R0(r,th,smid)) .* ...
    ( ...
    2.*(r.*cos(th)-smid).^2 ...
    - r.^2.*sin(th).^2 ...
    ) ./ R0(r,th,smid).^5 ...
    ) ...
    );

KEth = @(r,ph,th,smid) ...
    -1i./(4*pi*omega*eps) .* ...
    exp(-1i*k.*R0(r,th,smid)) .* ...
    ( ...
    r.*sin(th).*cos(th).*(r.*cos(th)-smid) .* ...
    ( ...
    3.*(1 + 1i*k.*R0(r,th,smid))./R0(r,th,smid).^5 ...
    - k^2./R0(r,th,smid).^3 ...
    ) ...
    - ...
    sin(th) .* ...
    ( ...
    k^2.*r.^2.*sin(th).^2 ./ R0(r,th,smid).^3 ...
    + ...
    (1 + 1i*k.*R0(r,th,smid)) .* ...
    ( ...
    2.*(r.*cos(th)-smid).^2 ...
    - r.^2.*sin(th).^2 ...
    ) ./ R0(r,th,smid).^5 ...
    ) ...
    );

Kf.Hph  = KHph;
Kf.Er   = KEr;
Kf.Eth  = KEth;